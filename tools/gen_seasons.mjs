// Generates firmware/corner-spider/include/seasons.h from the SEASONS table in
// simulator/index.html, so the simulator and the real prop run the same shows.
//   node tools/gen_seasons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(join(root, "simulator/index.html"), "utf8");
const m = html.match(/const SEASONS = (\{[\s\S]*?\n\});/);
if (!m) throw new Error("SEASONS table not found in simulator/index.html");
const SEASONS = Function(`return (${m[1]})`)();

const EYES = { off: "EYE_OFF", glow: "EYE_GLOW", full: "EYE_FULL", pulse: "EYE_PULSE", flicker: "EYE_FLICKER", blink: "EYE_BLINK", disco: "EYE_DISCO" };
const SPEED = ["SP_FAST", "SP_SLOW", "SP_MED"];
const q = (s) => JSON.stringify(s);

function step([op, a, b]) {
  switch (op) {
    case "MOVE": return `S_MOVE(${a}, ${SPEED[b]})`;
    case "WAITMOVE": return "S_WAITMOVE";
    case "WAIT": return `S_WAIT(${a})`;
    case "RWAIT": return `S_RWAIT(${a}, ${b})`;
    case "SND": return `S_SND(${a})`;
    case "SNDSTOP": return "S_SNDSTOP";
    case "EYES": return `S_EYES(${EYES[a]})`;
    case "WLED": return `S_WLED(${a})`;
    case "CHIT": return `S_CHIT(${a})`;
    case "WIGGLE": return `S_WIGGLE(${a}, ${b})`;
  }
  throw new Error("unknown op " + op);
}

let out = `#pragma once
// GENERATED by tools/gen_seasons.mjs from simulator/index.html. Do not edit by hand.
// Sound slot n of season k plays /<k+1 as 2 digits>/<n as 3 digits>.mp3 on the SD card.
// WLED slot n of season k recalls preset k*10+n.

`;
const seasons = Object.entries(SEASONS);
for (const [key, s] of seasons) {
  for (const [id, [, , steps]] of Object.entries(s.shows)) {
    out += `static const Step SEQ_${key}_${id}[] = {\n  ${steps.map(step).join(", ")}, S_END};\n`;
  }
  out += `static const Show SHOWS_${key}[] = {\n${Object.entries(s.shows).map(([id, [label, hint]]) => `  {${q(id)}, ${q(label)}, ${q(hint)}, SEQ_${key}_${id}},`).join("\n")}\n};\n`;
  out += `static const char *const SCARY_${key}[] = {${s.scary.map(q).join(", ")}};\n`;
  out += `static const char *const SOUNDS_${key}[] = {${s.sounds.map(q).join(", ")}};\n`;
  out += `static const char *const WLEDS_${key}[] = {${s.wled.map((w) => q(w.n)).join(", ")}};\n\n`;
}
out += `static const Season SEASONS[] = {\n${seasons
  .map(([key, s]) => `  {${q(key)}, ${q(s.label)}, ${q(s.char)}, SHOWS_${key}, ${Object.keys(s.shows).length}, SCARY_${key}, ${s.scary.length}, SOUNDS_${key}, WLEDS_${key}},`)
  .join("\n")}\n};\nstatic const int NUM_SEASONS = ${seasons.length};\n`;

writeFileSync(join(root, "firmware/corner-spider/include/seasons.h"), out);
console.log(`seasons.h: ${seasons.length} seasons, ${seasons.reduce((n, [, s]) => n + Object.keys(s.shows).length, 0)} shows`);
